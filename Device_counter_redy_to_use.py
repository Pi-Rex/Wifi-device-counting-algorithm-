# CREATE A TABLE THAT LINK THE INEQUALITY VALUE BETWEEN TWO BURST FOR EVERY BURST
def inequality_matrix_creator(data, n):

    # List of features used by the Block 2
    list_feature_Block_2 = ['ie1', 'ie50', 'ie45_ampduparam', 'ie45_capabilities', 'ie45_mcsset_highestdatarate',
                        'ie127_0', 'ie221_oui_0', 'ie221_type_0', 'ie221_oui_1', 'ie221_type_1', 'ie191', 'ie45_rxbitmask_32', 
                        'ie45_rxbitmask_8to15', 'ie221_oui_2', 'ie127_1', 'ie221_type_2', 'ie221_type_3', 'ie45_rxbitmask_33to38',
                        'ie45_rxbitmask_0to7', 'ie107_access_network_type']


    list_mac = list(data.keys()) # list MAC Addresses
    len_mac_address_list = len(list_mac) # len list MAC Addresses
    if len_mac_address_list == 1: # End condition
        return [list_mac]
    else:
        if n==0: # First condition, it create the header of the table
            data = data.copy()
            index = ['mac']
            list_mac.pop(len_mac_address_list-1)
            index += list_mac
            return [index] + inequality_matrix_creator(data, 1)
        else: # Here the matrix is created
            values_a = []
            mac_0 = list_mac[len_mac_address_list-1] # it starts from the last row
            subdata = data[mac_0] 
            for f in list_feature_Block_2: # Add the value of the features in values_a
                ver = existence_check(f, subdata)
                values_a.append(ver)
            inequality_vector = [mac_0] # The first element is the MAC
            list_mac.pop(len_mac_address_list-1) # The last value of the list_mac is removed
            for mac in list_mac: 
                inequality_value = 0 # Value of the inequality of two burst. Is initialisated to 0
                subdata_b = data[mac] # Subdata burst in comparison
                h=0 # index for the list values_a
                for feature in list_feature_Block_2:
                    valori_b = existence_check(feature, subdata_b)
                    if type(valori_b) == list and type(values_a[h]) == list: # In the event of both being list type
                            if feature == 'ie127_0': # case feature ie127_0
                                if len(values_a[h]) == len(valori_b):
                                    subtraction = [abs(g - k) for g, k in zip(values_a[h], valori_b)] # subtraction member by member # it's a list
                                    if sum(subtraction) != 0: # Case not every subtraction is 0 
                                        if subtraction.count(0) >= (len(subtraction)-2): # if there are less than two values different from 0
                                            difference_value = 'similar'
                                        else: # nore that two values different from 0
                                            difference_value = 'different'
                                    else: # if every value in the subtraction list is 0
                                        difference_value = 'equal'
                                else: # case the length of the two lists are different
                                    difference_value = 'different'
                            elif feature == 'ie1' or feature == 'ie50': # case feature ie1 o ie50
                                if len(values_a[h]) == len(valori_b): # if the length are equal
                                    subtraction = sum([abs(g - k) for g, k in zip(values_a[h], valori_b)]) # calculate the difference between the two lists
                                    if subtraction == 0:
                                        difference_value = 'equal'
                                    else:
                                        difference_value = 5000
                                elif len(values_a[h]) < len(valori_b): # if the length of 'a' is less than 'b'
                                    if is_sublist(values_a[h], valori_b) == True: # case 'b' is a sublist of 'a'
                                        difference_value = 'similar'
                                    else:
                                        sum_n = 0
                                        for x in values_a[h]: # search if the values in the list_a are present in the list_b
                                            if x not in valori_b:
                                                sum_n += 1
                                        if sum_n != 0:
                                            difference_value = 'different'
                                        else:
                                            difference_value = 'similar'
                                else: # if the length 'a' is more than 'b'
                                    if is_sublist(valori_b, values_a[h]) == True: # case 'a' is a sublist of 'b'
                                        difference_value = 'similar'
                                    else:
                                        sum_n = 0
                                        for x in valori_b:
                                            if x not in values_a[h]: # search if the values in the list_b are present in the list_a
                                                sum_n += 1
                                        if sum_n != 0:
                                            difference_value = 'different'
                                        else:
                                            difference_value = 'similar'
                            else: # for all others type list features
                                subtraction = abs(sum(valori_b) - sum(values_a[h]))
                                if subtraction != 0:
                                    difference_value = 'different'
                                else:
                                    difference_value = 'equal'
                    elif type(values_a[h]) == int and type(valori_b) == int: # case both type int
                        if (values_a[h] == MISSING_VALUE and valori_b == MISSING_VALUE): # case both not present
                            difference_value = 'equal'
                        elif (values_a[h] != MISSING_VALUE and valori_b == MISSING_VALUE): # case value-missing
                            difference_value = 'missing'
                        elif (values_a[h] == MISSING_VALUE and valori_b != MISSING_VALUE): # caso missing-value
                            difference_value = 'missing'
                        else: # case value-value
                            subtraction = abs(values_a[h] - valori_b)
                            if subtraction !=0:
                                difference_value = 'different'
                            else:
                                difference_value = 'equal'
                    else: # case different type
                        if type(values_a[h]) == list:
                            if valori_b == MISSING_VALUE: #if 'b' is missing
                                difference_value = 'missing'
                            else:
                                sum_var = sum(values_a[h])
                                subtraction = abs(sum_var - int(valori_b))
                                if subtraction !=0:
                                    difference_value = 'different'
                                else:
                                    difference_value = 'equal'
                        elif type(valori_b) == list:
                            if values_a[h] == MISSING_VALUE: # if 'a' is missing
                                difference_value = 'missing'
                            else:
                                sum_var = sum(valori_b)
                                subtraction = abs(sum_var - int(values_a[h]))
                                if subtraction !=0:
                                    difference_value = 'different'
                                else:
                                    difference_value = 'equal'
                    # Here are added the value of inequality between two feature
                    if difference_value != 'equal' and difference_value != 'missing' and difference_value != 'similar':
                        inequality_value += DISEQ_NUM
                    elif difference_value == 'missing':
                        inequality_value += DISEQ_MANC
                    elif difference_value == 'similar':
                        inequality_value += DISEQ_SIM
                    h += 1 # change feature
                    if inequality_value > DISEQ_UPPER_LIMIT:
                        break
                if inequality_value <= DISEQ_UPPER_LIMIT:
                    inequality_vector.append(round(inequality_value, 2))
                else:
                    inequality_vector.append(None)
            #print(inequality_vector)
            del data[mac_0]
            return [inequality_vector] + inequality_matrix_creator(data, 1)

