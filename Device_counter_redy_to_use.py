# RETURN THE VALUE OF DEVICES RESPONSABLE FOR THE GENERATION OF BURST WITH THE SAME VALUE OF THE FEATURES
# Take as input the list of the ratios between num_packets and delta_time
def function_group (ratios_list):
    ratios_list = sorted(ratios_list) # Sort the list
    group = [[ratios_list[0]]]
    i = 0
    threshold = 5
    for num in ratios_list[1:]:
        if num - group[-1][-1] <= threshold:
            group[-1].append(num)
        else:
            group.append([num])
        # threshold calculation
        threshold = (num - ratios_list[i])*5
        if threshold < 0.5:
            threshold = 0.5
        i+=1
    list_len_groups = []
    for sublist in group:
        list_len_groups.append(len(sublist))
    list_len_groups, group  = zip(*sorted(zip(list_len_groups, group), reverse = True))
    # Counting devices
    i = 1
    n_disp = 1
    list_len_groups = list(list_len_groups)
    n = 0
    if min(group[n]) == 0 and max(group[n]) == 0:
        list_len_groups.pop(0)
    if len(list_len_groups) != 0: 
        while i < len(list_len_groups):
            if list_len_groups[0]*PARAMETER_FILTER_FUNCTION <= list_len_groups[i]:
                n_disp += 1
            else:
                break
            i += 1
    return n_disp   

# DATASET REDUCTION FUNCTION
# Take as input data, step end dict_device
# In the end it return dict_device 
# Remove from data the burst with the same value of the features, remaning only different bursts
# In dict_device the different bursts are linked with the number of devices probably responsable for the generation of burst with the same value of the features
def funct_data_reduction (data, step, dict_device): #Prende in ingresso il dataset e il numero di passaggi che deve essere inizializzato a 0

    if len(data)==step: # end condition
        return dict_device

    else:
        #equal_brust_counter = 0 # It's used to know the number of times a burst with that structure is repeated
        MAC_addr = list(data.keys()) #list MAC addresses
        len_mac_address_list = len(MAC_addr) # len list MAC addresses
        
        mac_0 = MAC_addr[step] # mac ref
        subdata_a = data[MAC_addr[step]] # subdictionary that will be compared with the others
        values_a = [] # list of values of the feautures
        time = subdata_a['delta_time'] # value of delta_time
        num_packets = subdata_a['num_packets'] # value of num_packets
        if time != 0:
            rapporto = num_packets/time
        else: # if time is 0
            time = 0.0000000000000009
            rapporto = num_packets/time
        lista_rapporti = [rapporto]
        
        for f in LIST_FEATURE_BLOCK_1: # Add the values of the features in the list values_a
            ver_a = existence_check(f, subdata_a)
            values_a.append(ver_a)
        j= step + 1 # initialisation  j
        while j<len_mac_address_list: # In this cicle the features of every burst are compared
            if MAC_addr[0] != MAC_addr[j]: # check if the MAC addresses are the same
                subdata = data[MAC_addr[j]] 
                sum_difference = 0 # initialisation sum of the difference between the features
                h = 0 #  It's needed as index for the list 'values_a'
                for f in LIST_FEATURE_BLOCK_1: # Cicle where the values are compared
                    ver_b = existence_check(f, subdata) # Value of feature f in the burst with MAC_addr[j] as MAC
                    if type(values_a[h]) == list and type(ver_b) == list: # In the event the two features are list type 
                        difference = abs(sum(values_a[h]) - sum(ver_b))
                    elif type(values_a[h]) != type(ver_b): # In the event of different types
                        sum_difference = 5000
                        break
                    else: # In the event of int type
                        difference = abs(values_a[h] - ver_b)
                    sum_difference += difference
                    h += 1
                    if sum_difference != 0: # If sum is different from 0
                        break
                if sum_difference == 0: # If all the features are alike
                    del data[MAC_addr[j]] # Delete the burst duplicated
                    #count_probe_uguali += 1 # Add 1 to the count of equal bursts
                    time = subdata['delta_time']
                    num_packets = subdata['num_packets']
                    # num_packets delta_time ratio
                    if time != 0: 
                        rapporto = num_packets/time
                    else:
                        time = 0.0000000000000001
                        rapporto = num_packets/time
                    lista_rapporti.append(rapporto)
                j += 1 # Add 1 to go to the next burst
            else: # In the event the MAC address are equal
                j += 1 
        
        step += 1 # To go to the next burst ref
        dict_device[str(mac_0)] = function_group(lista_rapporti) # Add the burst ref to the dictionary
        return funct_data_reduction(data, step, dict_device) # The function is called back



