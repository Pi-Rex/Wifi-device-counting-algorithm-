# VERIFY THE EXISTENCE OF A FEATURE AND RETURN ITS VALUE
# Take as input the feature and the sub-dictionary of the burst

MISSING_VALUE = 12345
def existence_check(feature, subdata):
    if feature in subdata:
        if type(subdata[feature]) == str:
            return ast.literal_eval(subdata[feature]) # Return the value as a list
        else:
            if int(subdata[feature]) == 0: # If the value of the feature is 0
                return MISSING_VALUE
            else:
                return int(subdata[feature]) # Return the numerical value (int) of the feature
    else:
        return int(MISSING_VALUE) # If the feature is not present

#####################################
# VERIFY IF A IS A SUBLIST OF B (A<B)
def is_sublist(A, B):
    n, m = len(A), len(B)
    for i in range(m - n + 1):
        if B[i:i+n] == A:
            return True
    return False

