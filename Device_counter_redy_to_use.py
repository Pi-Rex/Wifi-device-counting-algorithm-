# CREATE A TABLE THAT LINK EVERY BURST TO THE BURST WITH WHOM HAVE THE SMOLLEST INEQUALITY VALUE 
def min_table_creator(df): # df is the table create in the block 2
        
    index_df = df.index # idex of the df table

    #Create a dictionary. It will be our table
    dict_min = {'Burst_ref': [], 'Burst_min': [], 'Value_min': []}
 
    # cicle for every row in df
    for row in index_df:
        couple_row = df.loc[[row]].stack()
        if row in df.columns:
                couple_coluns = df[[row]].stack()
                couple = pd.concat([couple_row, couple_coluns])
        else:
            couple = couple_row
        #print (couple)
        min_couple = couple.min() # min couple
        index_min_couple = couple.idxmin() # find the min burst
        dict_min['Burst_ref'].append(row)  
        if index_min_couple[0] == row:
            dict_min['Burst_min'].append(index_min_couple[1])
        else:
            dict_min['Burst_min'].append(index_min_couple[0])
        dict_min['Value_min'].append(min_couple)
    
    # Create a pandas dataframe from dict_min
    table_burst_min = pd.DataFrame(dict_min)
    #print(table_burst_min)

    return table_burst_min

def device_couter(table_burst_min, dict_devices): #def device_couter(table_burst_min, n_devices_MAC_fixed, dict_devices):

    index_table = table_burst_min.index
    num_devices = 0  # n_devices_MAC_fixed # numer of devices. Initialisated to the number of dev with the MAC fixed
    burst_seen = [] # save the burst already seen
    for index_row in index_table: # cicle for every row of the table
        burst_ref = table_burst_min.loc[index_row, 'Burst_ref'] # burst_ref
        if burst_ref not in burst_seen: # check if burst_ref has not already been seen
            burst_seen.append(burst_ref) # add burst_ref to burst_seen
            burst_min_ref = table_burst_min.loc[index_row, 'Burst_min'] # bust min of burst_ref
            if burst_min_ref not in burst_seen: # check if burst_min has not already been seen
                burst_min_min = table_burst_min.loc[table_burst_min['Burst_ref'] == burst_min_ref, 'Burst_min'].iloc[0] # bust min of burst_min_ref
                if burst_ref == burst_min_min: # if burst_ref is equal to burst_min_min
                    num_devices += max(dict_devices[burst_ref], dict_devices[burst_min_ref]) # max device of the two bursts
                    burst_seen.append(burst_min_ref) # add burst_min_ref to burst_seen
                else: 
                    num_devices += dict_devices[burst_ref]
            else:
                num_devices += dict_devices[burst_ref]
    return num_devices # total number of devices

